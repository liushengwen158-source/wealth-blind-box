# 回合引擎的测试。核心：暂停时时间必须真的冻住，恢复后不能跳变。
# 用假时钟「快进」，不用真的等 20 秒。

from round_engine import 回合引擎


def 造引擎():
    现在 = [0.0]
    引擎 = 回合引擎(时钟=lambda: 现在[0])
    return 引擎, 现在


def test_倒计时正常走():
    引擎, 现在 = 造引擎()
    引擎.开赛(总回合数=3, 回合毫秒=20_000)
    assert 引擎.状态 == "RUNNING"
    assert 引擎.剩余毫秒() == 20_000
    现在[0] = 5.0
    assert 引擎.剩余毫秒() == 15_000
    现在[0] = 25.0                    # 超时了也不该变成负数
    assert 引擎.剩余毫秒() == 0


def test_暂停时时间真的冻住了():
    引擎, 现在 = 造引擎()
    引擎.开赛(总回合数=3, 回合毫秒=20_000)
    现在[0] = 5.0
    assert 引擎.暂停() is True
    assert 引擎.剩余毫秒() == 15_000
    现在[0] = 500.0                   # 管理员把比赛晾了 495 秒
    assert 引擎.剩余毫秒() == 15_000   # 一毫秒都不能少
    assert 引擎.可交易() is False       # 暂停期间不能下单


def test_恢复后倒计时不跳变():
    引擎, 现在 = 造引擎()
    引擎.开赛(总回合数=3, 回合毫秒=20_000)
    现在[0] = 5.0
    引擎.暂停()
    现在[0] = 500.0
    assert 引擎.继续() is True
    assert 引擎.剩余毫秒() == 15_000   # 恢复瞬间不该变少
    现在[0] = 505.0
    assert 引擎.剩余毫秒() == 10_000   # 之后正常按 1 秒 1000 毫秒走


def test_回合推进到结束():
    引擎, 现在 = 造引擎()
    引擎.开赛(总回合数=2, 回合毫秒=10_000)
    assert 引擎.回合序号 == 1
    assert 引擎.进入下一回合() is True
    assert 引擎.回合序号 == 2
    assert 引擎.剩余毫秒() == 10_000
    assert 引擎.进入下一回合() is False      # 已经是最后一回合
    assert 引擎.状态 == "SETTLED"
    assert 引擎.可交易() is False
